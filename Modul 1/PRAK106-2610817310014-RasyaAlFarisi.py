a = 4
b = 8
c = 3

hasil_1 = int(a == b)
hasil_2 = int(b > c)
hasil_3 = int(a != c)

print(f"Variabel a bernilai {a}")
print(f"Variabel b bernilai {b}")
print(f"Variabel c bernilai {c}")
print(f"Apakah a sama dengan b ? jawabannya adalah {hasil_1}")
print(f"Apakah b lebih besar dari c ? jawabannya adalah {hasil_2}")
print(f"Apakah a tidak sama dengan c ? jawabannya adalah {hasil_3}")