putaran = 5
jarak_km = 14.0
pi = 3.141592653589793

keliling = jarak_km / putaran
jari_jari = keliling / (2 * pi)

print(f"Diketahui :")
print(f"Pak Dengklek mengelilingi taman = {putaran} Putaran")
print(f"Jarak tempuh Pak Dengklek = {jarak_km:.0f} Kilometer")
print(f"Jawaban :")
print(f"Jari-jari taman yang dikelilingi Pak Dengklek adalah {jari_jari:.2f} Kilometer")